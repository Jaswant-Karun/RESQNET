import { NextRequest, NextResponse } from "next/server";
import { Incident } from "@/types";
import { askGeminiQuestion } from "@/lib/server/gemini";

export interface AskAiRequestBody {
  question: string;
  incident: Incident;
  simulateError?: boolean;
}

export async function POST(req: NextRequest) {
  try {
    const body: AskAiRequestBody = await req.json();

    if (!body || !body.question || !body.incident) {
      return NextResponse.json(
        { error: "Missing required parameters (question, incident)." },
        { status: 400 }
      );
    }

    const { question, incident, simulateError } = body;

    if (simulateError) {
      return NextResponse.json({
        answer:
          `[Emergency Fallback Protocol Active] Offline response: Flood incident in ${incident.zoneName || "Zone A"} with water level ${incident.metrics.waterLevelMeters}m. Roads ${incident.blockedRoads?.join(", ") || "R1, R3"} are blocked. Evacuate via Route R2 to Shelter B.`,
        source: "FALLBACK",
        statusMessage: "AI service unavailable — emergency fallback activated.",
      });
    }

    const result = await askGeminiQuestion(question, incident, { timeoutMs: 7000 });

    return NextResponse.json({
      answer: result.answer,
      source: result.source,
      statusMessage:
        result.source === "GEMINI_AI"
          ? "AI Decision / Answer Generated by Gemini"
          : "AI service unavailable — emergency fallback activated.",
    });
  } catch (error) {
    console.error("[RESQNET Ask-AI Error]", error);
    return NextResponse.json({
      answer:
        "Emergency command fallback: Water level in Zone A is critical (2.4m). Road R2 is the designated clear evacuation passage to Shelter B.",
      source: "FALLBACK",
      statusMessage: "AI service unavailable — emergency fallback activated.",
    });
  }
}
