import { NextRequest, NextResponse } from "next/server";
import { Incident } from "@/types";
import {
  askGeminiQuestion,
  getDeterministicAiAnswer,
  AiQuestionContext,
} from "@/lib/server/gemini";
import {
  fetchFullEmergencyState,
  handleSpecialCommand,
  formatStructuredResponsePlan,
} from "@/lib/server/resqAiContext";

export interface AskAiRequestBody {
  question: string;
  incident: Incident;
  context?: AiQuestionContext;
  simulateError?: boolean;
  testCase?: "MISSING_KEY" | "QUOTA_EXCEEDED" | "INVALID_JSON" | "TIMEOUT" | "INVALID_RESPONSE";
}

export async function POST(req: NextRequest) {
  try {
    const body: AskAiRequestBody = await req.json();

    if (!body || !body.question || !body.incident) {
      return NextResponse.json(
        { error: "Missing required parameters (question, incident)." },
        { status: 400 }
      );
    }

    const { question, incident, context, simulateError, testCase } = body;

    // 1. Retrieve current situation-aware information from MongoDB/server state before answering
    const fullState = await fetchFullEmergencyState(context, incident);

    // 2. Immediate check for special command-style capabilities (/status, /risk, /resources, /incidents, /alerts, /plan, /summary)
    const slashResult = handleSpecialCommand(question, fullState);
    if (slashResult.handled && slashResult.answer) {
      return NextResponse.json({
        answer: slashResult.answer,
        source: "FALLBACK",
        statusMessage: "Deterministic Command-Center Telemetry Readout",
        fullState,
      });
    }

    // 3. Fallback / Test case simulation
    if (simulateError || testCase) {
      const fallbackAns = getDeterministicAiAnswer(question, incident, context, fullState);
      return NextResponse.json({
        answer: fallbackAns,
        source: "FALLBACK",
        statusMessage: "AI service unavailable — deterministic fallback engine active.",
        fullState,
      });
    }

    // 4. Situation-Aware Gemini Execution
    const result = await askGeminiQuestion(question, incident, context, {
      timeoutMs: 7000,
      fullState,
    });

    return NextResponse.json({
      answer: result.answer,
      source: result.source,
      statusMessage:
        result.source === "GEMINI_AI"
          ? "Situation-Aware Response Generated by Gemini"
          : "AI service unavailable — deterministic fallback engine active.",
      fullState,
    });
  } catch (error) {
    console.error("[RESQNET Ask-AI Error]", error);
    return NextResponse.json({
      answer:
        "Emergency command fallback: Zone A water level is 2.4m. Roads R1 and R3 are blocked. Proceed via designated safe Route R2 to Shelter B.\n\nData used:\n- Current incident\n- Fallback rule engine\nTimestamp: " +
        new Date().toISOString(),
      source: "FALLBACK",
      statusMessage: "AI service unavailable — deterministic fallback engine active.",
    });
  }
}
