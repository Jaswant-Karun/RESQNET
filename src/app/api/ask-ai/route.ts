import { NextRequest, NextResponse } from "next/server";
import { Incident } from "@/types";
import {
  askGeminiQuestion,
  getDeterministicAiAnswer,
  AiQuestionContext,
} from "@/lib/server/gemini";

export interface AskAiRequestBody {
  question: string;
  incident: Incident;
  context?: AiQuestionContext;
  simulateError?: boolean;
}

export async function POST(req: NextRequest) {
  try {
    const body: AskAiRequestBody = await req.json();

    if (!body || !body.question || !body.incident) {
      return NextResponse.json(
        { error: "Missing required parameters (question, incident)." },
        { status: 400 }
      );
    }

    const { question, incident, context, simulateError } = body;

    if (simulateError) {
      const fallbackAns = getDeterministicAiAnswer(question, incident, context);
      return NextResponse.json({
        answer: fallbackAns,
        source: "FALLBACK",
        statusMessage: "AI service offline — deterministic emergency fallback active.",
      });
    }

    const result = await askGeminiQuestion(question, incident, context, { timeoutMs: 7000 });

    return NextResponse.json({
      answer: result.answer,
      source: result.source,
      statusMessage:
        result.source === "GEMINI_AI"
          ? "Situation-Aware Response Generated by Gemini"
          : "Gemini offline — deterministic state fallback active.",
    });
  } catch (error) {
    console.error("[RESQNET Ask-AI Error]", error);
    return NextResponse.json({
      answer:
        "Emergency command fallback: Zone A water level is 2.4m. Roads R1 and R3 are blocked. Proceed via designated safe Route R2 to Shelter B.",
      source: "FALLBACK",
      statusMessage: "AI service unavailable — emergency fallback activated.",
    });
  }
}
